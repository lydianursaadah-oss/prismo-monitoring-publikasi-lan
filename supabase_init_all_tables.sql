-- 1. TABEL USERS (Akun Pengguna Sistem)
CREATE TABLE IF NOT EXISTS public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  username text NOT NULL,
  password text NOT NULL,
  nama text NOT NULL,
  jabatan text NOT NULL,
  unit text NOT NULL,
  role text NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT timezone ('utc'::text, now()),
  CONSTRAINT users_pkey PRIMARY KEY (id),
  CONSTRAINT users_username_key UNIQUE (username)
);

-- 2. TABEL PUBLIKASI (Publikasi LAN RI)
CREATE TABLE IF NOT EXISTS public.publikasi (
  id bigserial NOT NULL,
  no integer NULL,
  unit text NOT NULL,
  judul text NOT NULL,
  jenis text NULL DEFAULT ''::text,
  jadwal text NULL DEFAULT ''::text,
  tahun text NULL DEFAULT '2026'::text,
  cluster text NULL DEFAULT ''::text,
  jurnal text NULL DEFAULT ''::text,
  media text NULL DEFAULT ''::text,
  web_lan text NULL DEFAULT ''::text,
  web_unit text NULL DEFAULT ''::text,
  ig_lan text NULL DEFAULT ''::text,
  ig_unit text NULL DEFAULT ''::text,
  yt_lan text NULL DEFAULT ''::text,
  yt_unit text NULL DEFAULT ''::text,
  ket text NULL DEFAULT ''::text,
  created_at timestamp with time zone NULL DEFAULT now(),
  CONSTRAINT publikasi_pkey PRIMARY KEY (id)
);

-- 3. TABEL PRISMO PUBLICATION CALENDAR (Kalender Publikasi Terjadwal Humas)
CREATE TABLE IF NOT EXISTS public.prismo_publication_calendar (
  id text NOT NULL,
  source_type text NULL DEFAULT 'raw'::text,
  source_id text NOT NULL,
  judul text NOT NULL,
  unit text NOT NULL,
  cluster text NULL DEFAULT ''::text,
  pic text NULL DEFAULT ''::text,
  bentuk_naskah text NULL DEFAULT 'Laporan Lengkap & Policy Brief'::text,
  dokumen_url text NULL DEFAULT ''::text,
  publish_date text NULL DEFAULT ''::text,
  channels jsonb NULL DEFAULT '[]'::jsonb,
  channel_links jsonb NULL DEFAULT '{}'::jsonb,
  status_tayang text NULL DEFAULT 'terjadwal'::text,
  catatan_humas text NULL DEFAULT ''::text,
  updated_by text NULL DEFAULT 'Humas LAN RI'::text,
  updated_role text NULL DEFAULT 'humas'::text,
  created_at timestamp with time zone NULL DEFAULT now(),
  updated_at timestamp with time zone NULL DEFAULT now(),
  CONSTRAINT prismo_publication_calendar_pkey PRIMARY KEY (id)
);

-- 4. TABEL PRISMO PROPOSALS (Pengajuan & Verifikasi Proposal Kajian)
CREATE TABLE IF NOT EXISTS public.prismo_proposals (
  id text NOT NULL,
  judul text NOT NULL,
  unit text NOT NULL,
  jenis text NULL DEFAULT 'Survei'::text,
  cluster text NULL,
  latar_belakang text NULL,
  tujuan text NULL,
  pic text NULL,
  target_selesai date NULL,
  jadwal text NULL,
  tahun integer NULL DEFAULT 2026,
  dokumen_proposal text NULL,
  dokumen_jadwal text NULL,
  status text NULL DEFAULT 'diajukan'::text,
  diajukan_tgl date NULL DEFAULT CURRENT_DATE,
  diverifikasi_tgl date NULL,
  disetujui_tgl date NULL,
  checklist_admin jsonb NULL DEFAULT '{}'::jsonb,
  catatan_admin text NULL DEFAULT ''::text,
  keputusan_kepala text NULL,
  catatan_kepala text NULL DEFAULT ''::text,
  catatan_revisi text NULL DEFAULT ''::text,
  riwayat jsonb NULL DEFAULT '[]'::jsonb,
  created_at timestamp with time zone NULL DEFAULT now(),
  updated_at timestamp with time zone NULL DEFAULT now(),
  CONSTRAINT prismo_proposals_pkey PRIMARY KEY (id)
);

-- 5. TABEL MASTER UNITS (Master Data Unit Kerja LAN RI)
CREATE TABLE IF NOT EXISTS public.prismo_master_units (
  id serial NOT NULL,
  code text NOT NULL,
  name text NOT NULL,
  category text NULL DEFAULT 'Pusat Studi'::text,
  is_active boolean NULL DEFAULT true,
  sort_order integer NULL DEFAULT 0,
  created_at timestamp with time zone NULL DEFAULT timezone ('utc'::text, now()),
  updated_at timestamp with time zone NULL DEFAULT timezone ('utc'::text, now()),
  CONSTRAINT prismo_master_units_pkey PRIMARY KEY (id),
  CONSTRAINT prismo_master_units_code_key UNIQUE (code)
);

-- 6. TABEL MASTER MEDIA (Master Data Kanal Media Diseminasi)
CREATE TABLE IF NOT EXISTS public.prismo_master_media (
  id serial NOT NULL,
  code text NOT NULL,
  name text NOT NULL,
  type text NULL DEFAULT 'Media'::text,
  field_key text NULL DEFAULT ''::text,
  is_active boolean NULL DEFAULT true,
  sort_order integer NULL DEFAULT 0,
  created_at timestamp with time zone NULL DEFAULT timezone ('utc'::text, now()),
  updated_at timestamp with time zone NULL DEFAULT timezone ('utc'::text, now()),
  CONSTRAINT prismo_master_media_pkey PRIMARY KEY (id),
  CONSTRAINT prismo_master_media_code_key UNIQUE (code)
);

-- 7. TABEL MASTER JENIS (Master Data Jenis Kegiatan / Luaran)
CREATE TABLE IF NOT EXISTS public.prismo_master_jenis (
  id serial NOT NULL,
  code text NOT NULL,
  name text NOT NULL,
  description text NULL DEFAULT ''::text,
  is_active boolean NULL DEFAULT true,
  sort_order integer NULL DEFAULT 0,
  created_at timestamp with time zone NULL DEFAULT timezone ('utc'::text, now()),
  updated_at timestamp with time zone NULL DEFAULT timezone ('utc'::text, now()),
  CONSTRAINT prismo_master_jenis_pkey PRIMARY KEY (id),
  CONSTRAINT prismo_master_jenis_code_key UNIQUE (code)
);

-- 8. TABEL MASTER CLUSTERS (Master Data Klaster Kebijakan LAN RI)
CREATE TABLE IF NOT EXISTS public.prismo_master_clusters (
  id serial NOT NULL,
  code text NOT NULL,
  name text NOT NULL,
  description text NULL DEFAULT ''::text,
  color_hex text NULL DEFAULT '#2563eb'::text,
  is_placeholder boolean NULL DEFAULT false,
  is_active boolean NULL DEFAULT true,
  legacy_names jsonb NULL DEFAULT '[]'::jsonb,
  sort_order integer NULL DEFAULT 0,
  updated_by text NULL DEFAULT 'system'::text,
  created_at timestamp with time zone NULL DEFAULT timezone ('utc'::text, now()),
  updated_at timestamp with time zone NULL DEFAULT timezone ('utc'::text, now()),
  CONSTRAINT prismo_master_clusters_pkey PRIMARY KEY (id),
  CONSTRAINT prismo_master_clusters_code_key UNIQUE (code),
  CONSTRAINT prismo_master_clusters_name_key UNIQUE (name)
);

-- 9. TABEL ANNOUNCEMENTS (Pengumuman Sistem PRISMO)
CREATE TABLE IF NOT EXISTS public.prismo_announcements (
  id bigint NOT NULL,
  title text NOT NULL,
  description text NOT NULL,
  date text NULL,
  kategori text NULL DEFAULT 'Umum'::text,
  target_type text NULL DEFAULT 'Semua pengguna'::text,
  target_value text NULL DEFAULT ''::text,
  status text NULL DEFAULT 'Terbit'::text,
  start_date text NULL,
  end_date text NULL,
  attachment_url text NULL DEFAULT ''::text,
  author text NULL DEFAULT 'Admin DSPK2AN'::text,
  author_role text NULL DEFAULT 'admin_dspk2an'::text,
  created_at timestamp with time zone NULL DEFAULT now(),
  updated_at timestamp with time zone NULL DEFAULT now(),
  CONSTRAINT prismo_announcements_pkey PRIMARY KEY (id)
);

-- 10. TABEL INISIATIF AK DOSEN (Inisiatif Akademik Dosen & Scholar)
CREATE TABLE IF NOT EXISTS public.inisiatif_ak_dosen (
  id bigserial NOT NULL,
  no integer NULL,
  unit text NOT NULL,
  source_sheet text NOT NULL,
  judul text NOT NULL,
  jenis text NULL DEFAULT ''::text,
  jadwal_publikasi text NULL DEFAULT ''::text,
  tahun integer NULL,
  cluster_1 text NULL DEFAULT ''::text,
  cluster_2 text NULL DEFAULT ''::text,
  jurnal text NULL DEFAULT ''::text,
  media_online text NULL DEFAULT ''::text,
  website_lan text NULL DEFAULT ''::text,
  website_unit text NULL DEFAULT ''::text,
  instagram_lan text NULL DEFAULT ''::text,
  instagram_unit text NULL DEFAULT ''::text,
  youtube_lan text NULL DEFAULT ''::text,
  youtube_unit text NULL DEFAULT ''::text,
  media_televisi text NULL DEFAULT ''::text,
  catatan text NULL DEFAULT ''::text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  sitasi integer NOT NULL DEFAULT 0,
  CONSTRAINT inisiatif_ak_dosen_pkey PRIMARY KEY (id)
);

-- Indeks performa untuk inisiatif_ak_dosen
CREATE INDEX IF NOT EXISTS idx_inisiatif_ak_dosen_unit ON public.inisiatif_ak_dosen USING btree (unit);
CREATE INDEX IF NOT EXISTS idx_inisiatif_ak_dosen_tahun ON public.inisiatif_ak_dosen USING btree (tahun);

